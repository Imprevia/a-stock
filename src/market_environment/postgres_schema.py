def create_schema(engine: Engine) -> None:
    with engine.begin() as connection:
        # Several application workers can start at the same time during a
        # rollout. PostgreSQL serializes DDL through this transaction-scoped
        # advisory lock so the idempotent bootstrap cannot race on
        # CREATE/REPLACE FUNCTION or trigger creation.
        connection.execute(
            text("SELECT pg_advisory_xact_lock(hashtext('market-environment-schema-bootstrap'))")
        )
        for statement in SCHEMA_STATEMENTS:
            connection.execute(text(statement))
