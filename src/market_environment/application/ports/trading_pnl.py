"""Persistence and local image recognition contracts for the personal ledger."""

from collections.abc import Mapping, Sequence
from contextlib import AbstractContextManager
from dataclasses import dataclass
from datetime import date
from decimal import Decimal
from typing import Any, Protocol

from ...domain.models.trading_pnl import EvidenceBatch, Opening, Trade, ValuationEvidence

Row = Mapping[str, Any]


class PnlMarketEvidenceError(RuntimeError):
    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


@dataclass(frozen=True)
class PnlHistory:
    values: Sequence[ValuationEvidence]
    invalid_dates: frozenset[date] = frozenset()


@dataclass(frozen=True)
class PnlCorporateAction:
    date: date
    dividend_per_share: Decimal
    per_share_bonus: Decimal


@dataclass(frozen=True)
class PnlCorporateActions:
    security: str
    start: date
    end: date
    source: str
    events: tuple[PnlCorporateAction, ...]
    conflicts: frozenset[date] = frozenset()

    def missing_reason(self, day: date) -> str:
        if day in self.conflicts:
            return "fuyao-conflicting-action"
        if any(event.date == day for event in self.events):
            return "fuyao-action-entitlement-unverified"
        return "fuyao-action-coverage-unknown"


class PnlMarketEvidenceSource(Protocol):
    def trading_days(self) -> tuple[date, ...]: ...
    def closes(self, security: str, start: date, end: date) -> PnlHistory: ...
    def corporate_actions(self, security: str, start: date, end: date) -> PnlCorporateActions: ...


class RecognizedScreenshot(Protocol):
    digest: str
    image: bytes
    rows: list[dict]
    hints: list[str]


class TradingPnlRepository(Protocol):
    def state(self, *, lock: bool = False) -> Row: ...
    def set_opening(self, opening: Opening) -> None: ...
    def set_revision(self, revision: int) -> None: ...
    def operation(self, key: str) -> Row | None: ...
    def record_operation(self, key: str, kind: str, fingerprint: str, result: dict) -> None: ...
    def record_calculation_batch(self, batch_id: str, start: date) -> None: ...
    def calculation(self, batch_id: str) -> Row | None: ...
    def calculation_horizon(self) -> date | None: ...
    def calculation_start(self) -> date | None: ...
    def claim_calculation(self, batch_id: str, token: str, result: dict) -> None: ...
    def set_calculation_horizon(self, batch_id: str, end: date) -> None: ...
    def finish_calculation(self, batch_id: str, result: dict) -> None: ...
    def save_action_events(self, actions: PnlCorporateActions) -> None: ...
    def cached_action_window(self, security: str, start: date, end: date) -> bool: ...
    def action_issue(self, day: date, security: str) -> str | None: ...
    def audit(self, revision: int, data: dict) -> None: ...
    def cached_image(self, digest: str) -> Row | None: ...
    def put_image(self, image: RecognizedScreenshot) -> None: ...
    def put_draft(self, identifier: str, images: list[str]) -> str: ...
    def draft(self, identifier: str) -> Row | None: ...
    def finish_draft(self, identifier: str) -> None: ...
    def cleanup_images(self) -> None: ...
    def from_image(self, digest: str, number: int) -> Row | None: ...
    def strong_match(self, strong_id: str) -> Row | None: ...
    def candidates(self, trade: Trade) -> Sequence[Row]: ...
    def put_trade(self, trade: Trade, digest: str, number: int, strong_id: str | None, revision: int) -> int: ...
    def trade(self, identifier: int) -> Row | None: ...
    def correct_trade(self, identifier: int, trade: Trade, strong_id: str | None, revision: int) -> None: ...
    def trades(self, start: date, end: date, limit: int | None = None, after: int = 0) -> Sequence[Row]: ...
    def coverage(self, start: date, end: date) -> dict[date, str]: ...
    def put_coverage(self, days: list[date], kind: str) -> None: ...
    def clear_coverage(self, days: set[date]) -> None: ...
    def sessions(self, start: date, end: date) -> Mapping[date, Any]: ...
    def import_evidence(self, batch: EvidenceBatch) -> None: ...
    def valuations(self, start: date, end: date) -> dict[tuple[date, str], ValuationEvidence]: ...
    def original_closes(self, start: date, end: date, securities: list[str]) -> Sequence[Row]: ...
    def last_covered_date(self) -> date | None: ...
    def days(self, start: date, end: date) -> Sequence[Row]: ...
    def first_coverage_gap(self, before: date) -> date | None: ...
    def latest_day(self, before: date) -> Row | None: ...
    def reset_days(self, start: date) -> None: ...
    def put_day(self, day: date, revision: int, data: dict) -> None: ...


class TradingPnlStore(Protocol):
    def __call__(self, *, write: bool = False) -> AbstractContextManager[TradingPnlRepository]: ...
